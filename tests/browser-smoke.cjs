const server=http.createServer((req,res)=>{
  const url=decodeURIComponent(req.url.split('?')[0]);
  if(url==='/favicon.ico'){res.writeHead(204).end();return;}
  if(url==='/'){res.setHeader('Content-Type','text/html');res.end(fixture);return;}
  const file=url.startsWith('/core/')?path.resolve(core,url.slice(6)):path.resolve(root,'.'+url);
  if(!file.startsWith(root)&&!file.startsWith(core)){res.writeHead(403).end();return;}
  let st;try{st=fs.statSync(file)}catch{res.writeHead(404).end();return;}
  res.setHeader('Content-Type',mime[path.extname(file)]??'application/octet-stream');
  res.setHeader('Accept-Ranges','bytes');
  let start=0,end=st.size-1;
  const match=/bytes=(\d+)-(\d*)/.exec(req.headers.range??'');
  if(match){start=+match[1];end=match[2]?Math.min(+match[2],end):end;res.statusCode=206;res.setHeader('Content-Range',`bytes ${start}-${end}/${st.size}`);}
  res.setHeader('Content-Length',end-start+1);
  requests.push({url,start,end});
  fs.createReadStream(file,{start,end}).pipe(res);
});
